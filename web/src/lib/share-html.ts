import { currentLang, tr } from "@/lib/i18n";

/** One self-contained HTML page of a conversation's questions and answers: no scripts, styles inline. */

const STYLE = `
body{margin:0;background:#f6f3ec;color:#23201b;font:15px/1.7 "PingFang SC","Microsoft YaHei UI",system-ui,sans-serif}
main{max-width:46rem;margin:0 auto;padding:2rem 1.25rem 4rem}
h1{font:600 1.6rem/1.3 "Songti SC","Noto Serif SC",Georgia,serif;margin:0 0 .25rem}
.meta{color:#6b655a;font-size:.85rem;margin-bottom:1.5rem}
.q{background:#dcebe5;border-radius:1rem;padding:.6rem 1rem;margin:1.5rem 0 .75rem;white-space:pre-wrap}
.a table{border-collapse:collapse;margin:.75rem 0;display:block;overflow-x:auto}
.a th,.a td{border:1px solid #e3ddd0;padding:.35rem .6rem;text-align:left}
.a a{color:#2f6f5e}
.a pre,.a code{background:#f1ede3;border-radius:.375rem}
.a pre{padding:.75rem;overflow-x:auto}
.a code{padding:0 .25rem}
footer{margin-top:3rem;color:#6b655a;font-size:.8rem}
`;

function esc(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/** Copy of an answer's rendered HTML without buttons, menus and hover cards. */
export function cleanAnswerHtml(el: Element): string {
  const copy = el.cloneNode(true) as Element;
  copy.querySelectorAll("button, details, script, style, [role=tooltip], .pointer-events-none").forEach((n) => n.remove());
  copy.querySelectorAll("*").forEach((n) => {
    for (const attr of Array.from(n.attributes)) {
      if (attr.name.startsWith("on") || attr.name === "style" || attr.name === "class") n.removeAttribute(attr.name);
    }
    if (n.tagName === "A") {
      const href = n.getAttribute("href") ?? "";
      if (!/^https?:/i.test(href)) n.removeAttribute("href");
      else n.setAttribute("rel", "noreferrer");
    }
  });
  return copy.innerHTML;
}

export type Attachment =
  | { name: string; kind: "image"; dataUri: string }
  | { name: string; kind: "table"; rows: string[][]; total: number }
  | { name: string; kind: "text"; text: string }
  | { name: string; kind: "skipped"; why: string };

/** The files that go along with the answers: pictures inline, tables as tables, text as text. */
export function attachmentsHtml(items: Attachment[]): string {
  if (!items.length) return "";
  const parts = items.map((a) => {
    const head = `<h3>${esc(a.name)}</h3>`;
    if (a.kind === "image") return `${head}<img src="${a.dataUri}" alt="${esc(a.name)}" style="max-width:100%;background:#fff;border:1px solid #e3ddd0;border-radius:.375rem">`;
    if (a.kind === "table") {
      const [headRow, ...rest] = a.rows;
      const th = (headRow ?? []).map((c) => `<th>${esc(c)}</th>`).join("");
      const tr_ = rest.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join("")}</tr>`).join("");
      const more = a.total > rest.length ? `<p class="meta">${esc(tr("{total} rows in all; only the first {shown} are shown.", { total: a.total, shown: rest.length }))}</p>` : "";
      return `${head}<div class="a"><table><thead><tr>${th}</tr></thead><tbody>${tr_}</tbody></table>${more}</div>`;
    }
    if (a.kind === "text") return `${head}<div class="a"><pre>${esc(a.text)}</pre></div>`;
    return `${head}<p class="meta">${esc(a.why)}</p>`;
  });
  return `<h2>${esc(tr("Attachments"))}</h2>${parts.join("\n")}`;
}

export function buildShareHtml(title: string, turns: { prompt: string; answerHtml: string }[], when = new Date(), extraHtml = ""): string {
  const isZh = currentLang() === "zh";
  const lang = isZh ? "zh-CN" : "en";
  const body = turns
    .map((t) => `<div class="q">${esc(t.prompt)}</div><div class="a">${t.answerHtml || `<p>${esc(tr("(no answer in this round)"))}</p>`}</div>`)
    .join("\n");
  return `<!doctype html>
<html lang="${lang}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(title)}</title><style>${STYLE}</style></head>
<body><main><h1>${esc(title)}</h1><div class="meta">${esc(when.toLocaleString(isZh ? "zh-CN" : "en-US"))} · ${esc(tr("Generated by Biomni-Desk"))}</div>
${body}
${extraHtml}
<footer>${esc(tr("This is a saved answer page. It contains no scripts. The content is generated by a model; check citations against the original sources."))}</footer></main></body></html>`;
}
